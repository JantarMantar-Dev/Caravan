"""Scene layout pass: reference tile -> vector scene for the asset generators.

The cut-out layers (tools/layers.py) are a means, not the product: a 502 px
painting cut into pieces stays a 502 px painting, with trees missing the parts
other trees hid and rocks chopped at the waterline. This pass keeps only what
the reference is good for, the layout:

  hex       the tile outline (6 vertices)
  land      sand / grass / road regions as smooth vector paths, traced from
            the layer planes (they already have objects removed and holes filled)
  palette   colours sampled from the reference

and merges it with the hand-tuned asset list in tools/scenes/<tile>.json
(type, position, size, seed of every tree, rock, building, prop). The result,
assets/scenes/<tile>.json, is what src/gen/ draws as SVG at any resolution.

    python3 tools/scene.py fish_1
"""
import json, sys
from pathlib import Path
import numpy as np
from PIL import Image
from scipy import ndimage as ndi
from skimage import measure

ROOT = Path(__file__).resolve().parent.parent


def alpha(path):
    return np.asarray(Image.open(path).convert('RGBA'))[..., 3].astype(np.float32) / 255


def plane_mask(m, pid):
    p = next(p for p in m['planes'] if p['id'] == pid)
    a = alpha(ROOT / 'assets' / p['file'])
    full = np.zeros((m['h'], m['w']), np.float32)
    x, y = p['x'] + m['ox'], p['y'] + m['oy']
    full[y:y + p['h'], x:x + p['w']] = a
    return full


def trace(mask, sigma=2.2, tol=0.45, min_area=60):
    """Smooth closed paths around mask > 0.5, outer rings and holes alike."""
    soft = ndi.gaussian_filter(np.pad(mask, 2), sigma)
    rings = []
    for c in measure.find_contours(soft, 0.5):
        c = measure.approximate_polygon(c, tol)
        if len(c) < 4:
            continue
        xy = np.stack([c[:, 1] - 2, c[:, 0] - 2], 1)
        area = 0.5 * np.sum(xy[:-1, 0] * xy[1:, 1] - xy[1:, 0] * xy[:-1, 1])
        if abs(area) < min_area:
            continue
        rings.append([[round(float(x), 1), round(float(y), 1)] for x, y in xy[:-1]])
    return rings


def hex_outline(tile):
    a = alpha(ROOT / 'assets' / 'hex' / f'{tile}.avif')
    c = max(measure.find_contours(np.pad(a, 2), 0.5), key=len)
    for tol in np.arange(2, 30, 0.5):
        p = measure.approximate_polygon(c, tol)[:-1]
        if len(p) <= 6:
            break
    return [[round(float(x - 2), 1), round(float(y - 2), 1)] for y, x in p]


def main(tiles):
    man = json.loads((ROOT / 'assets/layers.json').read_text())
    for tile in tiles:
        m = man[tile]
        spec = json.loads((ROOT / 'tools/scenes' / f'{tile}.json').read_text())
        land = plane_mask(m, 'sand')
        grass = plane_mask(m, 'ground')
        road = plane_mask(m, 'road')
        scene = {
            'tile': tile, 'w': m['w'], 'h': m['h'],
            'hex': hex_outline(tile),
            'land': {'sand': trace(land), 'grass': trace(np.clip(grass - road, 0, 1)), 'road': trace(road, sigma=2.8)},
            **spec,
        }
        out = ROOT / 'assets/scenes' / f'{tile}.json'
        out.write_text(json.dumps(scene, separators=(',', ':')))
        print(tile, {k: len(v) for k, v in scene['land'].items()}, len(scene.get('assets', [])), 'assets ->', out.relative_to(ROOT))
    names = sorted(p.stem for p in (ROOT / 'assets/scenes').glob('*.json'))
    (ROOT / 'assets/scenes/index.js').write_text(
        '// generated by tools/scene.py\n' + ''.join(f"import {n} from './{n}.json';\n" for n in names) +
        'export const scenes = { ' + ', '.join(names) + ' };\n')


if __name__ == '__main__':
    main(sys.argv[1:] or ['fish_1'])
